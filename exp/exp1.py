"""Experiment 1: numerical simulation of BSDE-based fully-dynamic risk
measures with Lipschitz drivers and verification of h-longevity.

Reproduces, on simulated Brownian paths, the properties discussed around
Example 6 and Theorem 5 of the paper: cash subadditivity of the
fully-dynamic risk measure rho_tu(X) = E^g(-X|F_t) generated by the
Lipschitz driver g(t,y,z) = r_t*y^- + z, h-longevity (rho_tv >= rho_tu for
t <= u <= v) together with the explicit h-longevity index gamma(t,u,v,X) of
Theorem 5, failure of normalization for the non-normalized driver
gbar = g + 1, and the restriction / cash-additivity property that holds when
the driver does not depend on y and satisfies g(t,y,0) = 0.

Run: python -m exp.exp1
"""

from __future__ import annotations

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

from data.generate_synthetic import (
    simulate_brownian_paths,
    terminal_constant,
    terminal_from_bm,
    terminal_normal,
)
from src import config
from src.bsde_solver import grid_index, rho_from_bsde_affine_in_z, solve_bsde_affine_in_z_extended
from src.fully_dynamic import gamma_direct, gamma_theorem5

RESULTS_DIR = Path(__file__).resolve().parents[1] / "results"


# --------------------------------------------------------------------------
# Driver g(t,y,z) = h(t,y) + c(t)*z (Example 6) and variants: the driver is
# affine in z, so it is solved with the Girsanov-based solver of
# src.bsde_solver, which removes the linear-in-z term by a change of measure
# instead of estimating Z by regression (see that module's docstring).
# --------------------------------------------------------------------------
def r_constant(t: float) -> float:
    return config.EXP1_R_CONSTANT


def r_time_varying(t: float) -> float:
    return config.EXP1_R_A0 + config.EXP1_R_A1 * np.sin(2.0 * np.pi * t)


def c_one(_t: float) -> float:
    return 1.0


def h_example6(r_func):
    """h(t,y) = r_t*y^-, g(t,y,z) = h(t,y) + z (Example 6), Lipschitz with
    constant max(r_t, 1)."""

    def h(t, y):
        return r_func(t) * np.maximum(-y, 0.0)

    return h


def h_nonnormalized(r_func):
    """hbar(t,y) = r_t*y^- + 1, so gbar(t,0,0) = 1 != 0 (non-normalized)."""

    def h(t, y):
        return r_func(t) * np.maximum(-y, 0.0) + 1.0

    return h


def h_restriction(t, y):
    """h(t,y) = 0: g(t,y,z) = z is independent of y and g(t,y,0) = 0 for
    every y, so Proposition 4's restriction property applies and the
    generated risk measure is cash additive."""
    return np.zeros_like(y)


# --------------------------------------------------------------------------
# Terminal conditions X (F_u-measurable)
# --------------------------------------------------------------------------
def terminal_conditions(bm_path, times, u, n_paths, seed):
    return {
        "constant_0.0": terminal_constant(n_paths, 0.0),
        "constant_1.0": terminal_constant(n_paths, 1.0),
        "normal_0_1": terminal_normal(n_paths, 0.0, 1.0, seed=seed),
        "B_u": terminal_from_bm(bm_path.reshape(bm_path.shape[0], bm_path.shape[1], 1), times, u),
    }


def solve_rho(times, bm, t, u, h_func, c_func, x_at_u, basis_degree):
    rho_t, y_full = rho_from_bsde_affine_in_z(times, bm, t, u, h_func, c_func, -np.asarray(x_at_u), basis_degree)
    return rho_t, y_full


def cash_subadditivity_check(times, bm, t, u, h_func, c_func, x_at_u, m_list, basis_degree):
    """For m >= 0 verify rho_tu(X + m) >= rho_tu(X) - m (Definition 1, cash
    subadditivity): compare path-averaged rho since Y_t is F_t-measurable
    and nearly path-independent for t close to 0."""
    rho_base, _ = solve_rho(times, bm, t, u, h_func, c_func, x_at_u, basis_degree)
    base_mean = float(np.mean(rho_base))
    rows = []
    for m in m_list:
        rho_m, _ = solve_rho(times, bm, t, u, h_func, c_func, np.asarray(x_at_u) + m, basis_degree)
        shifted_mean = float(np.mean(rho_m))
        holds = shifted_mean >= base_mean - m - 1e-2
        rows.append({"m": m, "rho_X": base_mean, "rho_X_plus_m": shifted_mean,
                      "rho_X_minus_m_bound": base_mean - m, "cash_subadditivity_holds": holds})
    return rows


def h_longevity_and_gamma(times, bm, t, u, v, h_func, c_func, r_func, x_at_u, basis_degree):
    """Compute rho_tu, rho_tv, the direct gamma = rho_tv - rho_tu, and the
    explicit Theorem 5 formula, by pasting the bar-Y process of Eq. (17).

    rho_tv (the genuine Y_t^v) is computed by
    :func:`solve_bsde_affine_in_z_extended`: because X is F_u-measurable,
    the BSDE on (u, v] carries Z = 0 and reduces to a per-path backward ODE
    (see that function's docstring), which is solved exactly instead of by
    a single-state regression that cannot represent a payoff depending on
    an earlier time u.
    """
    it, iu, iv = grid_index(times, t), grid_index(times, u), grid_index(times, v)
    minus_x = -np.asarray(x_at_u)

    rho_tu, Y_tu = solve_rho(times, bm, t, u, h_func, c_func, x_at_u, basis_degree)
    rho_tv, Y_uv, Y_tv = solve_bsde_affine_in_z_extended(times, bm, t, u, v, h_func, c_func, minus_x, basis_degree)

    n_tail = iv - iu
    bar_y = np.concatenate([Y_tu, np.repeat(minus_x[:, None], n_tail, axis=1)], axis=1)
    assert bar_y.shape == Y_tv.shape

    sub_times = times[it: iv + 1]
    r_vals = np.array([r_func(s) for s in sub_times])  # (n_steps+1,)
    y_minus_v = np.maximum(-Y_tv, 0.0)
    y_minus_bar = np.maximum(-bar_y, 0.0)
    denom = Y_tv - bar_y
    diff = y_minus_v - y_minus_bar
    delta_y = np.where(
        np.abs(denom) > 1e-10,
        r_vals[None, :] * np.divide(diff, denom, out=np.zeros_like(diff), where=np.abs(denom) > 1e-10),
        r_vals[None, :] * np.where(Y_tv < 0.0, -1.0, 0.0),
    )
    g_minus_x_zero = r_vals[None, :] * np.maximum(np.asarray(x_at_u), 0.0)[:, None]

    gamma_formula = gamma_theorem5(times, bm, t, u, v, delta_y, 1.0, g_minus_x_zero, basis_degree)
    gamma_dir = gamma_direct(rho_tv, rho_tu)
    return rho_tu, rho_tv, gamma_dir, gamma_formula


def _parse_args() -> bool:
    import argparse

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--full", action="store_true",
        help="use the paper's full Monte Carlo configuration (EXP1_N_PATHS_PAPER) "
        "instead of the reduced run configuration (EXP1_N_PATHS_RUN)",
    )
    return parser.parse_args().full


def main() -> None:
    full = _parse_args()
    RESULTS_DIR.mkdir(exist_ok=True)
    n_paths = config.EXP1_N_PATHS_PAPER if full else config.EXP1_N_PATHS_RUN
    n_steps = config.EXP1_N_STEPS
    times, paths = simulate_brownian_paths(n_paths, n_steps, config.T_HORIZON, config.BM_DIMENSION, seed=config.RANDOM_SEED)
    bm = paths[:, :, 0]
    print(f"Simulated {n_paths} paths, {n_steps} steps, T={config.T_HORIZON}, d={config.BM_DIMENSION}")

    h_g = h_example6(r_constant)
    h_gbar = h_nonnormalized(r_constant)

    report: dict = {"n_paths": n_paths, "n_steps": n_steps, "r_constant": config.EXP1_R_CONSTANT}

    # 1-2-3. rho_tu(X) for several terminal conditions and horizons --------
    rho_table = []
    for u in config.EXP1_U_LIST + config.EXP1_V_LIST:
        term = terminal_conditions(bm, times, u, n_paths, config.RANDOM_SEED)
        for name, x_at_u in term.items():
            rho_t, _ = solve_rho(times, bm, 0.0, u, h_g, c_one, x_at_u, config.BASIS_DEGREE)
            rho_table.append({"t": 0.0, "u": u, "X": name, "rho_tu_mean": float(np.mean(rho_t)),
                               "rho_tu_std": float(np.std(rho_t))})
    report["rho_tu_table"] = rho_table

    # 4. Cash subadditivity --------------------------------------------------
    subadd_rows = []
    for t in [tt for tt in config.EXP1_T_LIST if tt < config.EXP1_U_LIST[0]]:
        u = config.EXP1_U_LIST[0]
        # X = B_u, a genuine F_u^B-measurable functional of the path (see note above).
        x_at_u = terminal_conditions(bm, times, u, n_paths, config.RANDOM_SEED)["B_u"]
        rows = cash_subadditivity_check(times, bm, t, u, h_g, c_one, x_at_u, config.EXP1_M_SUBADDITIVITY, config.BASIS_DEGREE)
        for row in rows:
            row.update({"t": t, "u": u})
        subadd_rows.extend(rows)
    report["cash_subadditivity"] = subadd_rows
    print("Cash subadditivity:", all(r["cash_subadditivity_holds"] for r in subadd_rows))

    # 5-6-7. h-longevity and Theorem 5 gamma --------------------------------
    longevity_rows = []
    for t in config.EXP1_T_LIST:
        for u in config.EXP1_U_LIST:
            if u <= t:
                continue
            for v in config.EXP1_V_LIST:
                if v < u:
                    continue
                # X = B_u: a genuine functional of the Brownian path (F_u^B-measurable).
                # An X drawn independently of the simulated path (e.g. "normal_0_1")
                # has a trivial conditional law E[X|F_t] = E[X] for every t < u, which
                # makes the regression-based backward recursion numerically degenerate
                # (Y collapses to an almost path-independent constant after a single
                # step) and destroys the step-by-step accumulation of the driver's
                # correction that Theorem 5's explicit formula relies on.
                x_at_u = terminal_conditions(bm, times, u, n_paths, config.RANDOM_SEED)["B_u"]
                rho_tu, rho_tv, gamma_dir, gamma_formula = h_longevity_and_gamma(
                    times, bm, t, u, v, h_g, c_one, r_constant, x_at_u, config.BASIS_DEGREE
                )
                rel_err = float(np.mean(np.abs(gamma_dir - gamma_formula)) / (np.mean(np.abs(gamma_dir)) + 1e-8))
                longevity_rows.append({
                    "t": t, "u": u, "v": v,
                    "rho_tu_mean": float(np.mean(rho_tu)), "rho_tv_mean": float(np.mean(rho_tv)),
                    "h_longevity_holds": bool(np.mean(rho_tv) >= np.mean(rho_tu) - 1e-2),
                    "gamma_direct_mean": float(np.mean(gamma_dir)),
                    "gamma_theorem5_mean": float(np.mean(gamma_formula)),
                    "gamma_nonneg": bool(np.mean(gamma_formula) >= -1e-2),
                    "relative_error_gamma": rel_err,
                })
    report["h_longevity"] = longevity_rows
    print("H-longevity holds for all tested triples:", all(r["h_longevity_holds"] for r in longevity_rows))
    print("Mean relative error gamma_direct vs Theorem 5 formula:",
          float(np.mean([r["relative_error_gamma"] for r in longevity_rows])))

    # 8. Non-normalized driver ------------------------------------------------
    zero = terminal_constant(n_paths, 0.0)
    rho_zero_g, _ = solve_rho(times, bm, 0.0, config.EXP1_U_LIST[0], h_g, c_one, zero, config.BASIS_DEGREE)
    rho_zero_gbar, _ = solve_rho(times, bm, 0.0, config.EXP1_U_LIST[0], h_gbar, c_one, zero, config.BASIS_DEGREE)
    report["normalization"] = {
        "rho_tu_zero_normalized_driver": float(np.mean(rho_zero_g)),
        "rho_tu_zero_nonnormalized_driver": float(np.mean(rho_zero_gbar)),
        "normalized_driver_is_normalized": bool(abs(np.mean(rho_zero_g)) < 1e-2),
        "nonnormalized_driver_is_normalized": bool(abs(np.mean(rho_zero_gbar)) < 1e-2),
    }
    print("Normalized driver rho(0) =", report["normalization"]["rho_tu_zero_normalized_driver"],
          "| non-normalized driver rho(0) =", report["normalization"]["rho_tu_zero_nonnormalized_driver"])

    # 9. Restriction property (g independent of y, g(t,y,0)=0) ---------------
    restriction_rows = []
    u, v = config.EXP1_U_LIST[0], config.EXP1_V_LIST[-1]
    x_at_u = terminal_conditions(bm, times, u, n_paths, config.RANDOM_SEED)["B_u"]
    rho_tu, _ = solve_rho(times, bm, 0.0, u, h_restriction, c_one, x_at_u, config.BASIS_DEGREE)
    rho_tv, _, _ = solve_bsde_affine_in_z_extended(times, bm, 0.0, u, v, h_restriction, c_one, -x_at_u, config.BASIS_DEGREE)
    restriction_rows.append({
        "u": u, "v": v,
        "rho_tu_mean": float(np.mean(rho_tu)), "rho_tv_mean": float(np.mean(rho_tv)),
        "restriction_holds": bool(abs(np.mean(rho_tu) - np.mean(rho_tv)) < 5e-2),
    })
    m = 0.7
    rho_tu_shift, _ = solve_rho(times, bm, 0.0, u, h_restriction, c_one, x_at_u + m, config.BASIS_DEGREE)
    restriction_rows.append({
        "cash_additivity_check_m": m,
        "rho_tu_X": float(np.mean(rho_tu)),
        "rho_tu_X_plus_m": float(np.mean(rho_tu_shift)),
        "rho_tu_X_minus_m_expected": float(np.mean(rho_tu)) - m,
        "cash_additivity_holds": bool(abs(float(np.mean(rho_tu_shift)) - (float(np.mean(rho_tu)) - m)) < 5e-2),
    })
    report["restriction_and_cash_additivity"] = restriction_rows
    print("Restriction property holds:", restriction_rows[0]["restriction_holds"],
          "| Cash additivity holds:", restriction_rows[1]["cash_additivity_holds"])

    with open(RESULTS_DIR / "exp1_metrics.json", "w") as f:
        json.dump(report, f, indent=2)

    # Plot: gamma(t,u,v,X) direct vs Theorem 5 formula ------------------------
    direct_vals = [r["gamma_direct_mean"] for r in longevity_rows]
    formula_vals = [r["gamma_theorem5_mean"] for r in longevity_rows]
    fig, ax = plt.subplots(figsize=(6, 6))
    ax.scatter(direct_vals, formula_vals, alpha=0.7)
    lims = [min(direct_vals + formula_vals), max(direct_vals + formula_vals)]
    ax.plot(lims, lims, "k--", label="y = x")
    ax.set_xlabel(r"$\gamma$ direct: $\rho_{tv}(X)-\rho_{tu}(X)$")
    ax.set_ylabel(r"$\gamma$ via Theorem 5 explicit formula")
    ax.set_title("Experiment 1: h-longevity index, direct vs. explicit formula")
    ax.legend()
    fig.tight_layout()
    fig.savefig(RESULTS_DIR / "exp1_gamma_comparison.png", dpi=150)
    plt.close(fig)

    print(f"Saved results/exp1_metrics.json and results/exp1_gamma_comparison.png")


if __name__ == "__main__":
    main()
